def trim_stale_authoritative_records(cur, conn, current_identifiers):
    """
    Deletes p_pycsw.records rows with source = 'authoritative' whose
    identifier is not backed by any file in the current metadata build -
    tables that have been dropped, renamed, or moved out of the a_* schemas
    since the last ingest. Uses '<> ALL(array)' rather than 'NOT IN (...)':
    psycopg2 adapts a Python list to a Postgres array cleanly, whereas an
    empty tuple passed to 'IN ()' is a SQL syntax error - this stays safe
    even in the (currently unreachable, load_metadata_files() already exits
    if empty) case of zero identifiers.
    """
    if not current_identifiers:
        print('\nTrim step skipped: no identifiers found in this build (nothing to compare against).')
        return 0
    try:
        cur.execute(
            "DELETE FROM p_pycsw.records "
            "WHERE source = 'authoritative' AND identifier <> ALL(%s) "
            "RETURNING identifier",
            (current_identifiers,),
        )
        removed = [row[0] for row in cur.fetchall()]
        conn.commit()
    except Exception as exc:
        conn.rollback()
        print(f'\nTrim step FAILED: {exc}')
        return 0

    if removed:
        print(f'\nTrimmed {len(removed)} stale authoritative record(s):')
        for identifier in removed:
            print(f'    - {identifier}')
    else:
        print('\nNo stale authoritative records found to trim.')
    return len(removed)


def ingest(dry_run):
    files = load_metadata_files()

    conn = cur = None
    if not dry_run:
        conn = psycopg2.connect(**DB_CONFIG)
        cur = conn.cursor()

    total = inserted = updated = skipped = failed = 0
    # Every identifier seen in this build, regardless of skip/failure status -
    # a table that exists but is currently poorly documented (e.g. missing
    # title) should not have its existing p_pycsw.records row trimmed away.
    seen_identifiers = []

    print(f'Found {len(files)} metadata file(s) in {METADATA_DIR}')
    if dry_run:
        print('Running in DRY-RUN mode - no database writes will be made.\n')
    print()

    for i, path in enumerate(files, 1):
        total += 1
        try:
            data = json.loads(path.read_text(encoding='utf-8'))
        except Exception as exc:
            failed += 1
            print(f'[{i}/{len(files)}] {path.name}: FAILED - could not parse JSON ({exc})')
            continue

        gemini_preview = data.get('gemini') or {}
        schema = gemini_preview.get('schema', '?')
        table = gemini_preview.get('table', '?')
        seen_identifiers.append(gemini_preview.get('unique_identifier') or f'{schema}/{table}')

        record, skip_reason = build_record(data)
        if record is None:
            skipped += 1
            print(f'[{i}/{len(files)}] {schema}/{table}: SKIP - {skip_reason}')
            continue

        if dry_run:
            print(f'[{i}/{len(files)}] {schema}/{table}: OK (dry-run)')
            print(f'    identifier   : {record["identifier"]}')
            print(f'    title        : {record["title"]}')
            print(f'    organisation : {record["organization"]}')
            print(f'    licence      : {record["accessconstraints"]}')
            print(f'    format       : {record["format"]}')
            print(f'    crs          : {record["crs"]}')
            print(f'    row_count    : {record["distancevalue"] or "unknown"}')
            print(f'    wkt_geometry : {record["wkt_geometry"] or "(no bbox available)"}')
            print(f'    mdsource     : {record["mdsource"] or "(no official URL)"}')
            print(f'    keywords     : {record["keywords"]}')
            print(f'    gemini_tier  : {(data.get("gemini") or {}).get("gemini_tier")}')
            print()
            continue

        try:
            cur.execute(UPSERT_SQL, record)
            was_inserted = cur.fetchone()[0]
            conn.commit()
            if was_inserted:
                inserted += 1
                print(f'[{i}/{len(files)}] {schema}/{table}: OK - INSERT')
            else:
                updated += 1
                print(f'[{i}/{len(files)}] {schema}/{table}: OK - UPDATE')
        except Exception as exc:
            failed += 1
            conn.rollback()
            print(f'[{i}/{len(files)}] {schema}/{table}: FAILED - {exc}')

    if dry_run:
        print('\nTrim step skipped in dry-run mode (no database connection to compare against).')
        deleted = 0
    else:
        deleted = trim_stale_authoritative_records(cur, conn, seen_identifiers)

    if cur:
        cur.close()
    if conn:
        conn.close()

    return total, inserted, updated, deleted, skipped, failed


def main():
    parser = argparse.ArgumentParser(
        description='Load metadata_builder/output/metadata/*.json records into p_pycsw.records.'
    )
    parser.add_argument(
        '--dry-run',
        action='store_true',
        help='Read and map every metadata file and print the result, without connecting to the database.',
    )
    args = parser.parse_args()

    dry_run = args.dry_run
    if not dry_run and _is_db_unconfigured():
        print(
            'GIS_DB_USER is not configured (still the YOUR_DB_USER placeholder or unset) - '
            'falling back to --dry-run. Set GIS_DB_HOST/PORT/NAME/USER/PASSWORD in .env and '
            'ensure VPN/network access to the real PostGIS server to perform a live ingest.\n'
        )
        dry_run = True

    total, inserted, updated, deleted, skipped, failed = ingest(dry_run)

    print(f"""
-----------------------------
Authoritative ingestion {'(dry-run) ' if dry_run else ''}complete
-----------------------------
Total processed  : {total}
Inserted         : {inserted}{' (n/a in dry-run)' if dry_run else ''}
Updated          : {updated}{' (n/a in dry-run)' if dry_run else ''}
Deleted (trimmed): {deleted}{' (n/a in dry-run)' if dry_run else ''}
Skipped          : {skipped}
Failed           : {failed}
-----------------------------
""")

    sys.exit(1 if failed else 0)


if __name__ == '__main__':
    main()
