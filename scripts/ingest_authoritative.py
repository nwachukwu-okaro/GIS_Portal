def _bbox_to_wkt(bbox):
    """Build a WKT polygon from a WGS84 bbox dict {xmin, ymin, xmax, ymax}."""
    if not bbox:
        return None
    try:
        xmin, ymin, xmax, ymax = bbox['xmin'], bbox['ymin'], bbox['xmax'], bbox['ymax']
    except (KeyError, TypeError):
        return None
    return (
        f'POLYGON(({xmin} {ymin},{xmin} {ymax},'
        f'{xmax} {ymax},{xmax} {ymin},{xmin} {ymin}))'
    )


def _build_anytext(gemini, organisation, schema, table, columns):
    """
    Rich searchable text blob — this is what the portal's ILIKE search
    (catalogue/views.py::_search_db_directly) matches against.

    Concatenates title, abstract, keywords, topic_category, organisation,
    schema/table names, and every column's name and description - not just
    table-level fields, so a search for a column-level concept (e.g. a
    specific attribute name) can still find the table.
    """
    parts = [
        gemini.get('title') or '',
        gemini.get('abstract') or '',
        ' '.join(gemini.get('keywords') or []),
        gemini.get('topic_category') or '',
        organisation,
        schema,
        table,
    ]
    parts.extend(c.get('name') or '' for c in columns)
    parts.extend(c.get('description') or '' for c in columns)
    return ' '.join(p for p in parts if p)


def load_metadata_files():
    """Every canonical *.json record built by metadata_builder/build.py."""
    if not METADATA_DIR.exists():
        print(f'{METADATA_DIR} does not exist - run metadata_builder/build.py first.', file=sys.stderr)
        sys.exit(1)
    files = sorted(METADATA_DIR.glob('*.json'))
    if not files:
        print(f'No .json files found in {METADATA_DIR} - run metadata_builder/build.py first.', file=sys.stderr)
        sys.exit(1)
    return files


PLACEHOLDER_COLUMN_DESCRIPTION = 'Source attribute; its precise meaning has not yet been documented.'


def _blank_to_none(value):
    """
    Recursively turns '' (and whitespace-only strings) into None, anywhere
    inside a dict/list. Used on the whole 'gemini' section per the cleanup
    spec: no empty strings, no "N/A"/"Not stated" placeholders - just null.
    """
    if isinstance(value, str):
        return value if value.strip() else None
    if isinstance(value, dict):
        return {key: _blank_to_none(v) for key, v in value.items()}
    if isinstance(value, list):
        return [_blank_to_none(v) for v in value]
    return value


def build_metadata_json(gemini_source, columns):
    """
    Builds the structured JSONB payload for p_pycsw.records.metadata_json:
    {gemini, columns} only. metadata_builder/build.py's own output (as of
    its "clean up output/metadata JSON" pass) already writes a 'gemini'
    section shaped almost identically to this one - organisation/source_url
    already flattened to plain strings, dataset_reference_date already split
    into date + date_type, use_constraints already combined from licence
    name/url. So this mostly re-selects the subset of fields this column's
    own contract calls for, rather than re-deriving anything: notably
    equivalent_scale, schema and table are present in build.py's gemini
    section but deliberately excluded from THIS column's contract (see the
    prior "cleanup metadata_json structure" task) - schema/table already
    have their own dedicated schema_name/table_name columns.
    """
    gemini = {
        'title': gemini_source.get('title'),
        'abstract': gemini_source.get('abstract'),
        'alternative_title': gemini_source.get('alternative_title'),
        'topic_category': gemini_source.get('topic_category'),
        'keywords': gemini_source.get('keywords') or [],
        'temporal_extent': gemini_source.get('temporal_extent'),
        'dataset_reference_date': gemini_source.get('dataset_reference_date'),
        'dataset_reference_date_type': gemini_source.get('dataset_reference_date_type'),
        'lineage': gemini_source.get('lineage'),
        'responsible_organisation': gemini_source.get('responsible_organisation'),
        'resource_locator': gemini_source.get('resource_locator'),
        'unique_identifier': gemini_source.get('unique_identifier'),
        'bounding_box': gemini_source.get('bounding_box'),
        'spatial_reference_system': gemini_source.get('spatial_reference_system'),
        'limitations_on_public_access': gemini_source.get('limitations_on_public_access'),
        'use_constraints': gemini_source.get('use_constraints'),
        'spatial_resolution': gemini_source.get('spatial_resolution'),
        'conformity': gemini_source.get('conformity'),
        'metadata_language': gemini_source.get('metadata_language'),
        'dataset_language': gemini_source.get('dataset_language'),
        'metadata_point_of_contact': gemini_source.get('metadata_point_of_contact'),
        'frequency_of_update': gemini_source.get('frequency_of_update'),
        'gemini_tier': gemini_source.get('gemini_tier'),
        'missing_mandatory_fields': gemini_source.get('missing_mandatory_fields') or [],
    }
    gemini = _blank_to_none(gemini)

    column_list = []
    for col in columns:
        description = col.get('description')
        if not description or description == PLACEHOLDER_COLUMN_DESCRIPTION:
            description = None
        column_list.append({
            # build.py's cleaned output already uses 'type' - the
            # data_type fallback only matters if this ever runs against an
            # older-format file left over from before that cleanup.
            'name': col.get('name'),
            'type': col.get('type') or col.get('data_type'),
            'description': description,
        })

    return {'gemini': gemini, 'columns': column_list}


ISO_NAMESPACES = {
    'gmd': 'http://www.isotc211.org/2005/gmd',
    'gco': 'http://www.isotc211.org/2005/gco',
}
for _prefix, _uri in ISO_NAMESPACES.items():
    ET.register_namespace(_prefix, _uri)

# gmd:contact is fixed (not per-record) - the catalogue's own point of
# contact, matching pycsw.cfg.example's [metadata:main] contact_* values.
ISO_CONTACT_ORGANISATION = 'Systra GIS Team'
ISO_CONTACT_EMAIL = 'gis_uk@systra.com'

_ISO_CODELIST_BASE = (
    'http://standards.iso.org/ittf/PubliclyAvailableStandards/'
    'ISO_19139_Schemas/resources/codelist/gmxCodelists.xml'
)
ISO_CHARACTER_SET_CODELIST = f'{_ISO_CODELIST_BASE}#MD_CharacterSetCode'
ISO_SCOPE_CODELIST = f'{_ISO_CODELIST_BASE}#MD_ScopeCode'
ISO_ROLE_CODELIST = f'{_ISO_CODELIST_BASE}#CI_RoleCode'
ISO_DATETYPE_CODELIST = f'{_ISO_CODELIST_BASE}#CI_DateTypeCode'


def _gmd(tag):
    return f"{{{ISO_NAMESPACES['gmd']}}}{tag}"


def _gco(tag):
    return f"{{{ISO_NAMESPACES['gco']}}}{tag}"


def _iso_char_string(parent, tag, text):
    """<gmd:{tag}><gco:CharacterString>{text}</gco:CharacterString></gmd:{tag}>"""
    if text is None or text == '':
        return None
    element = ET.SubElement(parent, _gmd(tag))
    char_string = ET.SubElement(element, _gco('CharacterString'))
    char_string.text = str(text)
    return element


def build_iso19139_xml(identifier, gemini):
    """
    Renders a minimal, valid ISO 19139 gmd:MD_Metadata XML document for
    p_pycsw.records.xml.

    pycsw is configured with profiles=apiso (pycsw/config/pycsw.cfg.example).
    Its apiso plugin decides whether to parse a record as ISO 19139 using
    "typename == 'gmd:MD_Metadata'" (see RECORD_TYPENAME above) - once it
    does, it uses owslib's MD_Metadata parser, which builds
    self.identification by walking gmd:identificationInfo's children and
    only appending an entry when that child's tag is exactly
    MD_DataIdentification/MD_ServiceIdentification/SV_ServiceIdentification;
    something downstream then indexes self.identification[0] unconditionally.
    A Dublin Core csw:Record document (this project's first attempt at this
    fix) has no such element at all, so self.identification stayed empty and
    [0] raised exactly "record serialization failed: list index out of
    range". This produces a real gmd:MD_DataIdentification instead, with
    exactly the sub-elements owslib's parser looks for (verified against
    OWSLib's iso.py source): citation title/date, abstract, descriptive
    keywords, language, topic category, and geographic extent.

    Built with ElementTree (not string formatting), so titles/abstracts
    containing '&', '<', '>' etc. can never produce malformed XML.
    """
    root = ET.Element(_gmd('MD_Metadata'))

    _iso_char_string(root, 'fileIdentifier', identifier)
    language = gemini.get('dataset_language') or 'eng'
    _iso_char_string(root, 'language', language)

    character_set = ET.SubElement(root, _gmd('characterSet'))
    character_set_code = ET.SubElement(character_set, _gmd('MD_CharacterSetCode'))
    character_set_code.set('codeList', ISO_CHARACTER_SET_CODELIST)
    character_set_code.set('codeListValue', 'utf8')
    character_set_code.text = 'utf8'

    hierarchy_level = ET.SubElement(root, _gmd('hierarchyLevel'))
    hierarchy_level_code = ET.SubElement(hierarchy_level, _gmd('MD_ScopeCode'))
    hierarchy_level_code.set('codeList', ISO_SCOPE_CODELIST)
    hierarchy_level_code.set('codeListValue', 'dataset')
    hierarchy_level_code.text = 'dataset'

    contact = ET.SubElement(root, _gmd('contact'))
    responsible_party = ET.SubElement(contact, _gmd('CI_ResponsibleParty'))
    _iso_char_string(responsible_party, 'organisationName', ISO_CONTACT_ORGANISATION)
    contact_info = ET.SubElement(responsible_party, _gmd('contactInfo'))
    ci_contact = ET.SubElement(contact_info, _gmd('CI_Contact'))
    address_wrapper = ET.SubElement(ci_contact, _gmd('address'))
    ci_address = ET.SubElement(address_wrapper, _gmd('CI_Address'))
    _iso_char_string(ci_address, 'electronicMailAddress', ISO_CONTACT_EMAIL)
    role = ET.SubElement(responsible_party, _gmd('role'))
    role_code = ET.SubElement(role, _gmd('CI_RoleCode'))
    role_code.set('codeList', ISO_ROLE_CODELIST)
    role_code.set('codeListValue', 'pointOfContact')
    role_code.text = 'pointOfContact'

    date_stamp = ET.SubElement(root, _gmd('dateStamp'))
    date_stamp_value = ET.SubElement(date_stamp, _gco('Date'))
    # Falls back to today (UTC) only when no dataset_reference_date exists -
    # dateStamp is metadata-record-required, unlike the citation date below.
    date_stamp_value.text = gemini.get('dataset_reference_date') or datetime.now(timezone.utc).date().isoformat()

    identification_info = ET.SubElement(root, _gmd('identificationInfo'))
    data_identification = ET.SubElement(identification_info, _gmd('MD_DataIdentification'))

    citation = ET.SubElement(data_identification, _gmd('citation'))
    ci_citation = ET.SubElement(citation, _gmd('CI_Citation'))
    _iso_char_string(ci_citation, 'title', gemini.get('title'))
    reference_date = gemini.get('dataset_reference_date')
    if reference_date:
        citation_date = ET.SubElement(ci_citation, _gmd('date'))
        ci_date = ET.SubElement(citation_date, _gmd('CI_Date'))
        date_element = ET.SubElement(ci_date, _gmd('date'))
        ET.SubElement(date_element, _gco('Date')).text = reference_date
        date_type = ET.SubElement(ci_date, _gmd('dateType'))
        date_type_code = ET.SubElement(date_type, _gmd('CI_DateTypeCode'))
        resolved_date_type = gemini.get('dataset_reference_date_type') or 'publication'
        date_type_code.set('codeList', ISO_DATETYPE_CODELIST)
        date_type_code.set('codeListValue', resolved_date_type)
        date_type_code.text = resolved_date_type

    _iso_char_string(data_identification, 'abstract', gemini.get('abstract'))

    keywords = gemini.get('keywords') or []
    if keywords:
        descriptive_keywords = ET.SubElement(data_identification, _gmd('descriptiveKeywords'))
        md_keywords = ET.SubElement(descriptive_keywords, _gmd('MD_Keywords'))
        for keyword in keywords[:20]:
            _iso_char_string(md_keywords, 'keyword', keyword)

    _iso_char_string(data_identification, 'language', language)

    topic_category = gemini.get('topic_category')
    if topic_category:
        topic_category_el = ET.SubElement(data_identification, _gmd('topicCategory'))
        ET.SubElement(topic_category_el, _gmd('MD_TopicCategoryCode')).text = topic_category

    bbox = gemini.get('bounding_box') or {}
    if all(key in bbox for key in ('xmin', 'ymin', 'xmax', 'ymax')):
        extent = ET.SubElement(data_identification, _gmd('extent'))
        ex_extent = ET.SubElement(extent, _gmd('EX_Extent'))
        geographic_element = ET.SubElement(ex_extent, _gmd('geographicElement'))
        geographic_bbox = ET.SubElement(geographic_element, _gmd('EX_GeographicBoundingBox'))
        for tag, value in (
            ('westBoundLongitude', bbox['xmin']), ('eastBoundLongitude', bbox['xmax']),
            ('southBoundLatitude', bbox['ymin']), ('northBoundLatitude', bbox['ymax']),
        ):
            bound_element = ET.SubElement(geographic_bbox, _gmd(tag))
            ET.SubElement(bound_element, _gco('Decimal')).text = str(value)

    return ET.tostring(root, encoding='unicode')


def build_record(data):
    """
    Map one canonical metadata_builder JSON record onto p_pycsw.records
    columns. Returns (record_dict, skip_reason) — record_dict is None when
    skip_reason is set.

    Reads from data['gemini'] and data['columns'] - metadata_builder/
    build.py's "clean up output/metadata JSON" pass made the source file
    itself {gemini, columns}-shaped, so there is no separate top-level
    title/publisher/geometry to read anymore.

    Two p_pycsw.records columns lose precision as a direct result of that
    source cleanup, since build.py's gemini section does not carry the raw
    values they used to come from:
      - accessconstraints previously held publisher.licence_name alone; now
        holds gemini.use_constraints (the same licence name, but combined
        with its URL), since the bare licence name is no longer available
        separately - only merged into use_constraints.
      - format/distanceuom previously included the PostGIS geometry type
        (e.g. 'PostGIS/MULTIPOLYGON'); geometry type is no longer present
        anywhere in the source file (build.py's Issue 1 cleanup explicitly
        removed the geometry section down to just CRS and bbox), so these
        fall back to a bare 'PostGIS' / empty geometry type. distancevalue
        (row count) is similarly no longer available and is left blank -
        catalogue/views.py's detail() overrides row_count/size with a live
        COUNT(*)/pg_total_relation_size() query for real (non-mock) runs
        regardless, so this mainly affects the mock-mode fallback display,
        but the detail page's Geometry sidebar row has no such live
        fallback and WILL go blank for authoritative records until
        geometry type is either restored to build.py's output or sourced
        some other way.
    """
    gemini = data.get('gemini') or {}
    columns = data.get('columns') or []

    title = (gemini.get('title') or '').strip()
    if not title:
        return None, 'missing title'

    schema = gemini.get('schema') or ''
    table = gemini.get('table') or ''
    identifier = gemini.get('unique_identifier') or (f'{schema}/{table}' if schema and table else '')
    if not identifier:
        return None, 'missing identifier'

    organisation = gemini.get('responsible_organisation') or ''
    accessconstraints = gemini.get('use_constraints') or DEFAULT_UK_LICENCE
    official_url = gemini.get('resource_locator') or ''
    crs = gemini.get('spatial_reference_system') or ''
    geometry_type = ''  # no longer present in build.py's output - see docstring
    row_count = None    # no longer present in build.py's output - see docstring

    metadata_json = build_metadata_json(gemini, columns)
    gemini_section = metadata_json.get('gemini') or {}
    temporal_extent = gemini_section.get('temporal_extent') or {}
    record_format = f'PostGIS/{geometry_type}' if geometry_type else 'PostGIS'

    record = {
        'identifier': identifier,
        'typename': RECORD_TYPENAME,
        'schema': RECORD_SCHEMA,
        'xml': build_iso19139_xml(identifier, gemini),
        'title': title,
        'abstract': gemini.get('abstract') or '',
        'keywords': ', '.join(gemini.get('keywords') or []),
        'publisher': organisation,
        'organization': organisation,
        'accessconstraints': accessconstraints,
        'mdsource': official_url,
        'type': 'dataset',
        'format': record_format,
        'wkt_geometry': _bbox_to_wkt(gemini.get('bounding_box')),
        'distancevalue': str(row_count) if row_count is not None else '',
        'distanceuom': geometry_type,
        'crs': crs,
        'source': 'authoritative',
        'links': official_url,
        'schema_name': schema,
        'table_name': table,
        'metadata_json': json.dumps(metadata_json, default=str),
        # Task 2: existing p_pycsw.records/pycsw-schema columns, populated
        # from the same metadata_json.gemini values rather than recomputed
        # separately, so they can never drift from what metadata_json shows.
        'topicategory': gemini_section.get('topic_category'),
        'lineage': gemini_section.get('lineage'),
        'time_begin': temporal_extent.get('begin'),
        'time_end': temporal_extent.get('end'),
        'title_alternate': gemini_section.get('alternative_title'),
    }
    record['anytext'] = _build_anytext(gemini, organisation, schema, table, columns)
    return record, None


