#!/usr/bin/env python
"""
ingest_authoritative.py

Loads the canonical per-table metadata records built by metadata_builder/
(metadata_builder/output/metadata/*.json) into the pycsw catalogue
(p_pycsw.records), so the portal can search and display authoritative
a_* datasets alongside whatever ingest_minio.py / ingest_postgis.py load.

p_pycsw.records is the single source of truth for portal search, QGIS
MetaSearch, and the LLM agent - the agent no longer reads
metadata_builder/output/metadata/*.json directly. Those files are still this
script's INPUT (metadata_builder/build.py's canonical output), but every
GEMINI2 field and column description they contain is also written into the
metadata_json JSONB column here (see build_metadata_json()), structured as
{gemini, columns} - deliberately just those two sections; technical details
that don't serve the portal/agent read path (capabilities, discovery_hints,
provenance, quality, build) stay out of metadata_json. A handful of existing
p_pycsw.records/pycsw-schema columns (topicategory, lineage, time_begin,
time_end, title_alternate) are also populated from the same gemini values.
Run scripts/migrate_add_metadata_json.py once before the first run of this
script, to add schema_name/table_name/metadata_json to p_pycsw.records.

Credentials: read from .env using the same GIS_DB_HOST/PORT/NAME/USER/
PASSWORD/SSLMODE variables as the rest of this project (portal/settings.py's
GIS_DB_CONFIG, catalogue/views.py's _db_connect(), metadata_builder/
extract_schema.py's DB_CONFIG) — not the hardcoded YOUR_DB_* placeholders in
ingest_postgis.py.template, since this project's convention is .env-based
credentials for every script that doesn't ship with the repo pre-filled.

Metadata source: every *.json file in metadata_builder/output/metadata/,
resolved relative to this script's own location (../metadata_builder/output/
metadata), so the same script reads the bundled mock/dev records unmodified
and, once deployed, the real records generated by metadata_builder/build.py
on the production server.

After upserting every record from the current metadata build, any
p_pycsw.records row with source = 'authoritative' whose identifier is not
backed by any file in this build is deleted (trimmed) - this removes records
for tables that have been dropped or renamed since the last ingest, so
p_pycsw.records never drifts from what's actually in metadata_builder/output/
metadata/. Trimming is skipped in --dry-run mode (no database connection to
compare against).

Usage:
    python scripts/ingest_authoritative.py
    python scripts/ingest_authoritative.py --dry-run   # map + print, no DB writes

If GIS_DB_USER is unset or still the YOUR_DB_USER placeholder (e.g. on a dev
laptop with no VPN access to the real PostGIS server), the script
automatically runs in dry-run mode instead of failing outright.
"""
